#!/usr/bin/env python3
"""Known-fixture worker checks; Linux pressure tests require --resource-tests.

Never starts the daemon, reads its database/credentials, discovers units, or
stops a unit not generated by this invocation. Guest code is synthetic only.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import platform
import re
import signal
import subprocess
import sys
import time
import uuid

ENGINE = "wasmi-2.0.0"
POLICY = "pure-i32-v1"
MEMORY = 128 * 1024 * 1024
ADD = '(module (func (export "calc") (param i32 i32) (result i32) local.get 0 local.get 1 i32.add))'
CASES = [{"args": [2, 3], "expected": 5}, {"args": [-7, 2], "expected": -5}]


class CheckFailure(Exception):
    pass


def digest(path: Path) -> str:
    hasher = hashlib.sha256()
    with path.open("rb") as source:
        for block in iter(lambda: source.read(1024 * 1024), b""):
            hasher.update(block)
    return hasher.hexdigest()


def payload(request: dict) -> bytes:
    return json.dumps(request, ensure_ascii=False, separators=(",", ":")).encode()


def parse_response(output: bytes) -> dict:
    if len(output) > 128 * 1024:
        raise CheckFailure("worker_response_bound")
    try:
        response = json.loads(output)
    except (ValueError, UnicodeError) as error:
        raise CheckFailure("worker_response_protocol") from error
    if not isinstance(response, dict):
        raise CheckFailure("worker_response_protocol")
    return response


def successful(response: dict, operation: str, enforced: bool) -> dict:
    if (response.get("status") != "ok" or response.get("engine") != ENGINE
            or response.get("policy") != POLICY
            or response.get("resources", {}).get("enforced") is not enforced
            or response.get("outcome", {}).get("op") != operation):
        raise CheckFailure("worker_identity_or_outcome")
    return response["outcome"]


def local(binary: Path, request: dict, require_cgroup: bool = False) -> dict:
    environment = {"LANG": "C"}
    if os.name == "nt" and "SystemRoot" in os.environ:
        environment["SystemRoot"] = os.environ["SystemRoot"]
    command = [str(binary), "wasm-worker"]
    if require_cgroup:
        command.append("--require-cgroup")
    try:
        completed = subprocess.run(command, input=payload(request), stdout=subprocess.PIPE,
                                   stderr=subprocess.DEVNULL, env=environment, timeout=8,
                                   creationflags=subprocess.CREATE_NO_WINDOW if os.name == "nt" else 0)
    except (OSError, subprocess.TimeoutExpired) as error:
        raise CheckFailure("standalone_worker_not_bounded") from error
    response = parse_response(completed.stdout)
    if completed.returncode != (0 if response.get("status") == "ok" else 2):
        raise CheckFailure("worker_exit_protocol")
    return response


def valid_unit(unit: str) -> bool:
    match = re.fullmatch(r"dsh-wasm-([0-9a-f-]{36})\.service", unit)
    if not match:
        return False
    try:
        identifier = uuid.UUID(match.group(1))
        return identifier.version == 4 and str(identifier) == match.group(1)
    except ValueError:
        return False


def manager_env() -> dict:
    return {key: value for key, value in os.environ.items()
            if key in {"XDG_RUNTIME_DIR", "DBUS_SESSION_BUS_ADDRESS"}} | {"LANG": "C"}


def manager(*arguments: str, timeout: float = 3) -> subprocess.CompletedProcess:
    try:
        result = subprocess.run(["/usr/bin/systemctl", "--user", *arguments],
                                stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
                                env=manager_env(), timeout=timeout)
    except (OSError, subprocess.TimeoutExpired) as error:
        raise CheckFailure("systemd_manager_unavailable") from error
    if len(result.stdout) > 16384:
        raise CheckFailure("systemd_manager_protocol")
    return result


def show(unit: str) -> dict:
    if not valid_unit(unit):
        raise CheckFailure("invalid_owned_unit")
    text = manager("show", "--no-pager", "--property=LoadState,ActiveState,SubState,Type,"
                   "ControlGroup,MainPID,MemoryMax,MemorySwapMax,TasksMax,RuntimeMaxUSec,"
                   "TimeoutStopUSec,Result", "--", unit).stdout.decode("utf-8", "strict")
    properties = dict(line.split("=", 1) for line in text.splitlines() if "=" in line)
    if "LoadState" not in properties:
        raise CheckFailure("systemd_manager_protocol")
    return properties


def group_path(unit: str, group: str) -> Path:
    parts = group.split("/")
    if (not group.startswith("/") or "\\" in group or parts[-1] != unit
            or any(part in {"", ".", ".."} for part in parts[1:])):
        raise CheckFailure("cgroup_membership_unverified")
    return Path("/sys/fs/cgroup") / str(PurePosixPath(group)).lstrip("/")


def verify(unit: str, properties: dict, binary: Path) -> dict:
    expected = {"LoadState": "loaded", "ActiveState": "active", "SubState": "running",
                "Type": "exec", "MemoryMax": str(MEMORY), "MemorySwapMax": "0", "TasksMax": "1"}
    if any(properties.get(key) != value for key, value in expected.items()):
        raise CheckFailure("manager_limits_unverified")
    if properties.get("RuntimeMaxUSec") not in {"5s", "5000ms", "5000000us", "5000000"}:
        raise CheckFailure("runtime_limit_unverified")
    if properties.get("TimeoutStopUSec") not in {"1s", "1000ms", "1000000us", "1000000"}:
        raise CheckFailure("stop_limit_unverified")
    root = group_path(unit, properties.get("ControlGroup", ""))
    for name, value in [("memory.max", str(MEMORY)), ("memory.swap.max", "0"), ("pids.max", "1")]:
        if (root / name).read_text().strip() != value:
            raise CheckFailure("kernel_limits_unverified")
    pid = properties.get("MainPID", "")
    if not pid.isdigit() or int(pid) <= 0:
        raise CheckFailure("worker_pid_unverified")
    # Type=exec initially acknowledges env(1); wait for its exec into the fixed
    # binary before examining that process's final, deliberately empty environment.
    if (Path("/proc") / pid / "exe").resolve() != binary:
        raise CheckFailure("worker_exec_pending")
    # Inspect only this invocation's worker, never daemon/manager environments.
    environment = (Path("/proc") / pid / "environ").read_bytes().split(b"\0")
    if sorted(item for item in environment if item) != [b"LANG=C"]:
        raise CheckFailure("worker_environment_not_empty")
    return {"memory_max_bytes": MEMORY, "swap_max_bytes": 0, "pids_max": 1,
            "runtime_max_usec": 5_000_000, "environment_keys_count": 1}


def inactive(unit: str) -> bool:
    properties = show(unit)
    state = properties.get("ActiveState")
    if properties.get("LoadState") != "not-found" and state not in {"inactive", "failed"}:
        return False
    group = properties.get("ControlGroup", "")
    if not group:
        return True
    events = group_path(unit, group) / "cgroup.events"
    try:
        return "populated 0" in events.read_text().splitlines()
    except FileNotFoundError:
        return True


def stop_exact(unit: str) -> None:
    if not valid_unit(unit):
        raise CheckFailure("invalid_owned_unit")
    try:
        manager("stop", "--", unit)
    except CheckFailure:
        pass
    for _ in range(15):
        if inactive(unit):
            try:
                manager("reset-failed", "--", unit)
            except CheckFailure:
                pass
            return
        time.sleep(0.1)
    raise CheckFailure("resource_cleanup_unconfirmed")


def resource(binary: Path, request: dict, report: dict, save) -> tuple[dict | None, dict, str]:
    unit = f"dsh-wasm-{uuid.uuid4()}.service"
    report["pending_units"].append(unit)
    save()  # A killed checker still leaves the exact unit it owns in its report.
    command = ["/usr/bin/systemd-run", "--user", "--wait", "--pipe", "--quiet", "--unit", unit,
               "--property=Type=exec", "--property=MemoryMax=128M", "--property=MemorySwapMax=0",
               "--property=TasksMax=1", "--property=RuntimeMaxSec=5s", "--property=TimeoutStopSec=1s",
               "--property=KillMode=control-group", "--property=NoNewPrivileges=yes",
               "--property=OOMPolicy=kill", "--", "/usr/bin/env", "-i", "LANG=C", str(binary),
               "wasm-worker", "--require-cgroup"]
    child = None
    try:
        child = subprocess.Popen(command, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                                 stderr=subprocess.DEVNULL, env=manager_env())
        verified = None
        for _ in range(30):
            properties = show(unit)
            if properties.get("ActiveState") == "active":
                try:
                    verified = verify(unit, properties, binary)
                    break
                except CheckFailure as error:
                    if str(error) != "worker_exec_pending":
                        raise
            if properties.get("LoadState") == "loaded" and properties.get("ActiveState") in {"failed", "inactive"}:
                raise CheckFailure("resource_worker_did_not_start")
            time.sleep(0.03)
        if verified is None:
            raise CheckFailure("resource_worker_start_unverified")
        output, _ = child.communicate(payload(request), timeout=8)
        if len(output) > 128 * 1024:
            raise CheckFailure("worker_response_bound")
        result = show(unit).get("Result", "")
        response = parse_response(output) if output else None
        if response and response.get("status") == "ok":
            resources = response.get("resources", {})
            if (resources.get("unit") != unit or resources.get("enforced") is not True
                    or resources.get("memory_max_bytes") != MEMORY
                    or resources.get("swap_max_bytes") != 0 or resources.get("pids_max") != 1):
                raise CheckFailure("worker_resource_proof_mismatch")
        return response, verified, result
    except (OSError, subprocess.TimeoutExpired, ValueError) as error:
        raise CheckFailure("resource_worker_failed") from error
    finally:
        # Stop/reap the launcher first; stopping only it does not stop a service.
        if child is not None:
            if child.poll() is None:
                child.kill()
            try:
                child.wait(timeout=1)
            except subprocess.TimeoutExpired:
                pass
        stop_exact(unit)
        report["pending_units"].remove(unit)
        save()


def run(args) -> dict:
    binary = args.binary.resolve(strict=True)
    report = {"checker_sha256": digest(Path(__file__).resolve()), "binary_sha256": digest(binary),
              "declared_source_sha": args.source_sha, "platform": {"os": platform.system(),
              "arch": platform.machine()}, "engine": ENGINE, "policy": POLICY,
              "model_calls": 0, "resource_tests_requested": args.resource_tests,
              "resource_enforcement": "not_tested", "pending_units": [], "checks": []}

    def save():
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    def check(name, assertion):
        passed = bool(assertion)
        report["checks"].append({"name": name, "passed": passed})
        save()
        if not passed:
            raise CheckFailure("check_failed")

    save()
    try:
        response = local(binary, {"op": "compile_and_test", "wat": ADD, "cases": CASES})
        compiled = successful(response, "compile_and_test", False)
        import base64
        wasm = base64.b64decode(compiled["wasm_base64"], validate=True)
        check("standalone_real_engine_compiles_and_runs_explicit_tests",
              compiled["results"] == [5, -5] and compiled["wat_sha256"] == hashlib.sha256(ADD.encode()).hexdigest()
              and compiled["wasm_sha256"] == hashlib.sha256(wasm).hexdigest())
        response = local(binary, {"op": "execute", "wasm_base64": compiled["wasm_base64"], "args": [9, 4]})
        check("standalone_fresh_process_revalidates_and_executes_binary", successful(response, "execute", False)["result"] == 13)
        wrapping = local(binary, {"op": "compile_and_test", "wat": ADD,
                         "cases": [{"args": [2147483647, 1], "expected": -2147483648},
                                   {"args": [-2147483648, -1], "expected": 2147483647}]})
        check("i32_boundary_arithmetic_has_wasm_wrapping_semantics", successful(wrapping, "compile_and_test", False)["results"] == [-2147483648, 2147483647])
        forbidden = {
            "imports": '(import "private-canary-wasi" "fd_write" (func))',
            "linear_memory": '(memory 1)', "table": '(table 1 funcref)',
            "global": '(global i32 (i32.const 0))',
            "start_function": '(func $s (loop $again br $again)) (start $s)',
        }
        for name, declaration in forbidden.items():
            wat = ADD.replace("(module ", "(module " + declaration + " ", 1)
            rejected = local(binary, {"op": "compile_and_test", "wat": wat, "cases": CASES})
            check(f"reject_{name}_before_instantiation", rejected == {"status": "error", "code": "policy_rejected"})
        for name, wat in {
            "float_operator": '(module (func (export "calc") (param i32 i32) (result i32) f64.const 1 drop i32.const 5))',
            "wrong_export": ADD.replace('"calc"', '"other"'), "component": '(component)',
        }.items():
            check(f"reject_{name}", local(binary, {"op": "compile_and_test", "wat": wat, "cases": CASES})["status"] == "error")
        endless = '(module (func (export "calc") (param i32 i32) (result i32) (loop $again br $again) unreachable))'
        check("infinite_loop_consumes_finite_real_vm_fuel", local(binary, {"op": "compile_and_test", "wat": endless, "cases": CASES}) == {"status": "error", "code": "out_of_fuel"})
        recursion = '(module (func $f (export "calc") (param i32 i32) (result i32) local.get 0 local.get 1 call $f i32.const 1 i32.add))'
        check("non_tail_recursion_traps_on_stack_limit", local(binary, {"op": "compile_and_test", "wat": recursion, "cases": CASES}) == {"status": "error", "code": "stack_limit"})
        failed = local(binary, {"op": "compile_and_test", "wat": ADD, "cases": [{"args": [2, 3], "expected": 4}] * 2})
        check("test_failure_does_not_return_a_compiled_artifact", failed == {"status": "error", "code": "test_failed"})
        oversized = local(binary, {"op": "compile_and_test", "wat": " " * 65537, "cases": CASES})
        check("source_size_is_bounded", oversized == {"status": "error", "code": "input_too_large"})
        check("raw_errors_or_source_are_not_echoed", local(binary, {"op": "compile_and_test", "wat": "private-canary-not-wat", "cases": CASES}) == {"status": "error", "code": "invalid_wat"})
        check("unenforced_cli_cannot_trigger_resource_pressure", local(binary, {"op": "resource_probe", "kind": "memory"}) == {"status": "error", "code": "resource_unavailable"})
        if args.resource_tests:
            if platform.system() != "Linux":
                raise CheckFailure("resource_tests_require_linux")
            response, proof, _ = resource(binary, {"op": "compile_and_test", "wat": ADD, "cases": CASES}, report, save)
            enforced = successful(response or {}, "compile_and_test", True)
            check("real_systemd_cgroup_and_environment_limits_precede_untrusted_input", proof["environment_keys_count"] == 1 and enforced["results"] == [5, -5])
            response, _, _ = resource(binary, {"op": "execute", "wasm_base64": enforced["wasm_base64"], "args": [19, 4]}, report, save)
            check("enforced_fresh_worker_executes_verified_artifact", successful(response or {}, "execute", True)["result"] == 23)
            response, _, _ = resource(binary, {"op": "compile_and_test", "wat": endless, "cases": CASES}, report, save)
            check("enforced_worker_preserves_vm_fuel_boundary", response == {"status": "error", "code": "out_of_fuel"})
            response, _, result = resource(binary, {"op": "resource_probe", "kind": "memory"}, report, save)
            check("real_128MiB_cgroup_oom_is_reaped_without_a_success_response", response is None and result == "oom-kill")
            response, _, result = resource(binary, {"op": "resource_probe", "kind": "timeout"}, report, save)
            check("real_five_second_runtime_limit_terminates_and_reaps_worker", response is None and result == "timeout")
            report["resource_enforcement"] = "linux_systemd_user_verified"
        report["passed"] = True
    except (CheckFailure, OSError, ValueError, KeyError, TypeError, KeyboardInterrupt) as error:
        report["passed"] = False
        report["error_code"] = str(error) if isinstance(error, CheckFailure) else "checker_failed"
    save()
    return report


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", type=Path, required=True)
    parser.add_argument("--report", type=Path, required=True)
    parser.add_argument("--source-sha", help="Previously verified deployment SHA; recorded as declared, not inferred from binary")
    parser.add_argument("--resource-tests", action="store_true", help="Explicit Linux-only OOM/5-second timeout tests in this invocation's own units")
    args = parser.parse_args()
    if args.source_sha and not re.fullmatch(r"[0-9a-f]{40}", args.source_sha):
        parser.error("--source-sha must be a full lowercase commit SHA")
    signal.signal(signal.SIGINT, lambda *_: (_ for _ in ()).throw(KeyboardInterrupt()))
    if hasattr(signal, "SIGTERM"):
        signal.signal(signal.SIGTERM, lambda *_: (_ for _ in ()).throw(KeyboardInterrupt()))
    try:
        report = run(args)
    except (OSError, ValueError):
        print(json.dumps({"passed": False, "error_code": "checker_setup_failed"}))
        return 1
    print(json.dumps({"passed": report["passed"], "checks": len(report["checks"]),
                      "resource_enforcement": report["resource_enforcement"]}))
    return 0 if report["passed"] else 1


if __name__ == "__main__":
    sys.exit(main())
